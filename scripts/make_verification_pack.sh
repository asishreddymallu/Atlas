#!/usr/bin/env bash
# Builds the verification test-case pack: a reviewable copy of every test asset
# of Atlas (GoogleTest sources and case tables, the independent verification
# checkers, the example programs), with a README, a generated COVERAGE.md and
# the last recorded results.
#
# Everything is taken from `git archive` of a committed tree (HEAD by default),
# so the pack does not depend on the working tree and is reproducible.
# Nothing is built or run; the results are copied from the repo's records.
#
# usage: scripts/make_verification_pack.sh [<commit-ish>]
# output: dist/Atlas_Verification_TestCases/ and dist/Atlas_Verification_TestCases.zip
# needs: git, python3 (standard library only), zip
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
REV=${1:-HEAD}
NAME=Atlas_Verification_TestCases
DIST=$ROOT/dist
PACK=$DIST/$NAME
COMMIT=$(git -C "$ROOT" rev-parse --verify "$REV^{commit}")

for tool in git python3 zip; do
  command -v "$tool" >/dev/null || { echo "error: $tool not found" >&2; exit 1; }
done

STAGE=$(mktemp -d)
trap 'rm -rf "$STAGE"' EXIT
git -C "$ROOT" archive --format=tar "$COMMIT" test verification examples \
  scripts/run_verification.sh scripts/test.sh docs/TESTING.md README.md \
  | tar -x -C "$STAGE"

rm -rf "$PACK" "$DIST/$NAME.zip"
mkdir -p "$PACK"
cp -r "$STAGE/test" "$PACK/01_unit_tests"
# verification/out/ (run outputs) is git-ignored, so git archive never has it.
cp -r "$STAGE/verification" "$PACK/02_independent_verification"
cp -r "$STAGE/examples" "$PACK/03_example_programs"

python3 -I - "$STAGE" "$PACK" "$COMMIT" "$(git -C "$ROOT" show -s --format=%cs "$COMMIT")" \
  "$(git -C "$ROOT" log -1 --format='%cs %h' -S'608 s' "$COMMIT" -- docs/TESTING.md)" <<'PY'
import os, re, sys
stage, pack, commit, cdate, ctest_rec = sys.argv[1:6]
T = os.path.join(stage, "test")
V = os.path.join(stage, "verification")
E = os.path.join(stage, "examples")

def read(p):
    with open(p, encoding="utf-8", errors="replace") as f:
        return f.read()

TEST_RE = re.compile(r"^\s*(TEST|TEST_F|TEST_P|TYPED_TEST|TYPED_TEST_P)\s*\(\s*(\w+)\s*,\s*(\w+)", re.M)
INC_ROW = re.compile(r"^\s*\{\s*\"", re.M)

# ---- unit test files ----
files = sorted(f for f in os.listdir(T) if f.endswith((".cpp", ".h", ".inc")))
info = {}
for f in files:
    txt = read(os.path.join(T, f))
    macros = TEST_RE.findall(txt)
    info[f] = {
        "txt": txt,
        "tests": len(macros),
        "suites": sorted({m[1] for m in macros}),
        "rows": len(INC_ROW.findall(txt)) if f.endswith(".inc") else 0,
    }
cpp = [f for f in files if f.endswith(".cpp") and f != "test_main.cpp"]
incs = [f for f in files if f.endswith(".inc")]
n_macros = sum(info[f]["tests"] for f in cpp)
n_rows = sum(info[f]["rows"] for f in incs)
data_files = []
for d, _, fs in os.walk(os.path.join(T, "data")):
    data_files += [os.path.relpath(os.path.join(d, x), T) for x in fs]

# tables generated by an independent checker: the list check_tables.py proves
ct = read(os.path.join(V, "tables", "check_tables.py"))
generated = re.findall(r'\("([\w/]+\.py)",\s*"test/([\w.]+)"\)', ct)
gen_targets = {t for _, t in generated}

def cases(f):
    i = info[f]
    return f"{i['tests']} TEST" + (f", {i['rows']} rows" if i["rows"] else "")

# ---- examples ----
ex = []
for d, _, fs in os.walk(E):
    for x in fs:
        rel = os.path.relpath(os.path.join(d, x), E)
        if x.endswith((".s", ".asm", ".lua")):
            ex.append(rel)
ex.sort()
def first_comment(rel):
    for line in read(os.path.join(E, rel)).splitlines():
        s = line.strip()
        m = re.match(r"^(#|;|--|//)\s*(.*)", s)
        if m and m.group(2).strip("-# ").strip():
            return m.group(2).strip()
        if s and not m:
            return None
    return None
def users(rel):
    base = os.path.basename(rel)
    return sorted(f for f in cpp if base in info[f]["txt"])

# expected results the repo already records for examples
recorded = {}
lab = read(os.path.join(T, "cache_lab_cases.inc"))
for prog in sorted(set(re.findall(r'\{"(\w+)", "(\w+)"', lab))):
    recorded.setdefault(prog[0] + ".s", []).append(prog[1])
sched = read(os.path.join(E, "scheduler", "README.md"))
sched_rows = re.findall(r"^\| ([^|]*?) \| (\d+) \| (\d+) \|$", sched, re.M)

out = []
out.append("# Example programs\n")
out.append(f"Generated by `scripts/make_verification_pack.sh` from commit `{commit[:12]}`.\n")
out.append("'What it exercises' is the program's own first comment line; a program without a header "
           "comment says so. 'Used by' lists the unit-test files that name the program.\n")
out.append("| Program | What it exercises | Used by (test files) |")
out.append("| --- | --- | --- |")
for rel in ex:
    c = first_comment(rel) or "(no header comment in the file)"
    u = ", ".join(f"`{x}`" for x in users(rel)) or "none"
    out.append(f"| `{rel}` | {c.replace('|', '/')} | {u} |")
out.append("\n## Expected results already recorded in the repo\n")
out.append("- **Cache lab** (`cache_lab/*.s`): L1 hits, misses and evictions per preset are in "
           "`01_unit_tests/cache_lab_cases.inc` (generated by `cachemodel.py` + `miniiss.py`, independent "
           "of the simulator). Presets recorded per program:")
for p, cfgs in sorted(recorded.items()):
    out.append(f"  - `{p}`: {', '.join(cfgs)}")
out.append("- **Scheduler** (`scheduler/load_use_*.s`), cycle counts from `scheduler/README.md`:\n")
out.append("| Configuration | Original | Reordered |\n| --- | ---: | ---: |")
for r in sched_rows:
    out.append(f"| {r[0]} | {r[1]} | {r[2]} |")
out.append("\n- **Profiler metrics** for the 9 cache-lab programs and the 4 scheduler demos are in "
           "`01_unit_tests/profiler_metrics_cases.inc` (generated by the mini ISS).")
out.append("- The other programs have no recorded expected values outside the test files that use them.")
open(os.path.join(pack, "03_example_programs", "INDEX.md"), "w").write("\n".join(out) + "\n")

# ---- COVERAGE.md ----
ROWS = [
  ("ISA: I (base integer)", r"^(shift|pc_relative|li_|call_tail|memory_endian|operandless|pseudo|program_end|comment_syntax|lexer|parser)", None),
  ("ISA: M (mul/div)", r"div_rem", r"\b(mul|mulh|mulhsu|mulhu|div|divu|rem|remu|mulw|divw|divuw|remw|remuw)\s+x\d"),
  ("ISA: F (single)", r"float|fclass|fflags|fdiv|fp_|flw|canonical_nan|f_extension|_fp", r"\bf(add|sub|mul|div|sqrt|cvt|eq|lt|le|class|sgnj\w*)\.s\s+[fx]"),
  ("ISA: D (double)", r"double|d_extension", r"\bf(add|sub|mul|div|sqrt|cvt|eq|lt|le|class|sgnj\w*)\.d\s+[fx]"),
  ("ISA: RV64 W forms", r"w_forms", r"\b(addw|subw|addiw|sllw|srlw|sraw|slliw|srliw|sraiw)\s+x\d"),
  ("ISA: CSR / ecall", r"csr|ecall|syscall", r"\bcsrr[wsc]i?\s+x\d|\becall\b"),
  ("Model: single-cycle (RVSS)", None, r"RVSSProcessor|RVSSVM|\"rvss\""),
  ("Model: 5-stage NH-NF", None, r"RV5StageProcessorNHNF|nh_nf|NH_NF"),
  ("Model: 5-stage NH-F", None, r"RV5StageProcessorNHF|nh_f\b|NH_F\b"),
  ("Model: 5-stage H-NF", None, r"RV5StageProcessorHNF|(?<![nN])h_nf|(?<![N_])H_NF"),
  ("Model: 5-stage H-F", None, r"RV5StageProcessorHF|(?<![nN])h_f\b|(?<![N_])H_F\b"),
  ("Hazards and forwarding", r"hazard|forward|fwd|stall|hdu", None),
  ("Branches and jumps", r"branch|control_flow|call_tail|pc_relative|jump", r"\b(beq|bne|blt|bge|bltu|bgeu|jal|jalr)\s+x\d"),
  ("Caches and replacement policies", r"cache|policy|policies|eviction", None),
  ("Cache Lab", r"cache_lab", None),
  ("Scheduler", r"scheduler", None),
  ("Profiler metrics", r"profiler", None),
  ("UI: Editor tab", None, r"ui/editor_tab/"),
  ("UI: Processor tab", None, r"ui/processor_tab/"),
  ("UI: Timing grid", None, r"ui/timing_grid/"),
  ("UI: Cache tab", None, r"ui/cache_tab/"),
  ("UI: Memory tab", None, r"ui/memory_tab/"),
  ("UI: Register table", None, r"ui/register_table/"),
  ("UI: Profiler tab", None, r"ui/profiler_tab/"),
  ("UI: Problems panel", None, r"ui/problems_panel/"),
  ("UI: Ribbon", None, r"ui/ribbon/"),
  ("UI: Themes", None, r"ui/theme/"),
  ("UI: Compiler tab", None, r"ui/compiler_tab/"),
]
cov = ["# Coverage matrix\n",
  f"Generated by `scripts/make_verification_pack.sh` from commit `{commit[:12]}` ({cdate}). "
  "Nothing in this file is written by hand.\n",
  "**How a file is matched to a row:** the file name matches the row's name pattern, or the file's "
  "text matches the row's content pattern (both shown, case-insensitive for names). Files under "
  "`01_unit_tests/` only (`.cpp` tests and `.inc` case tables; `test_main.cpp` excluded).\n",
  "**What the counts are:** `TEST` = number of `TEST`/`TEST_F`/`TEST_P`/`TYPED_TEST` macros in the "
  "file (a parameterised macro registers many CTest cases, so this is a lower bound); `rows` = case rows "
  "in an `.inc` table. A match means the file mentions the topic, not that it checks it exhaustively.\n",
  f"Totals: {len(cpp)} test `.cpp` files, {n_macros} TEST macros, {len(incs)} `.inc` tables with "
  f"{n_rows} rows.\n",
  "| Area | Name pattern | Content pattern | Files | TEST macros | .inc rows | Test files (cases) |",
  "| --- | --- | --- | ---: | ---: | ---: | --- |"]
pool = cpp + incs
for name, npat, cpat in ROWS:
    hit = []
    for f in pool:
        ok = bool(npat and re.search(npat, f, re.I))
        if not ok and cpat:
            ok = bool(re.search(cpat, info[f]["txt"]))
        if ok:
            hit.append(f)
    tm = sum(info[f]["tests"] for f in hit); tr = sum(info[f]["rows"] for f in hit)
    lst = "; ".join(f"`{f}` ({cases(f)})" for f in hit) or "none"
    cov.append(f"| {name} | `{(npat or '-').replace('|', '¦')}` | `{(cpat or '-').replace('|', '¦')}` | {len(hit)} | {tm} | {tr} | {lst} |")
cov.append("\n(`¦` in a pattern stands for regex alternation `|`.)\n")
cov.append("## Expectation tables generated by an independent checker\n")
cov.append("These are the files `02_independent_verification/tables/check_tables.py` regenerates and compares; "
           "their expected values come from the generator, never from Atlas.\n")
cov.append("| Test file | Generator | Cases |\n| --- | --- | --- |")
for g, t in generated:
    cov.append(f"| `{t}` | `{g}` | {cases(t) if t in info else 'missing'} |")
cov.append("\n## Every test file\n")
cov.append("| File | Cases | Suites |\n| --- | --- | --- |")
for f in pool:
    cov.append(f"| `{f}` | {cases(f)} | {', '.join(info[f]['suites']) or '-'} |")
open(os.path.join(pack, "COVERAGE.md"), "w").write("\n".join(cov) + "\n")

# ---- RESULTS.txt ----
res = read(os.path.join(V, "RESULTS.md"))
exp = read(os.path.join(V, "expected_summary.txt"))
testing = read(os.path.join(stage, "docs", "TESTING.md"))
m = re.search(r"The suite has [^\n]*\n[^\n]*", testing)
r = ["ATLAS - LAST RECORDED RESULTS",
     f"Copied by scripts/make_verification_pack.sh from commit {commit} ({cdate}).",
     "Nothing was re-run to make this file.", "",
     "1. GoogleTest suite (ctest, serial)",
     f"   Source: docs/TESTING.md, last changed on this line in commit {ctest_rec or 'unknown'}:",
     "   " + (m.group(0).replace("\n", " ") if m else "(line not found)"), "",
     "2. Independent verification (scripts/run_verification.sh)",
     "   Source: verification/RESULTS.md, reproduced in full below.",
     "", res, "",
     "3. verification/expected_summary.txt (the pinned summary the run is compared with)", "", exp]
open(os.path.join(pack, "RESULTS.txt"), "w").write("\n".join(r) + "\n")

# ---- README.md ----
vfiles = sum(len(fs) for _, _, fs in os.walk(V))
rows_tbl = [
 ("GoogleTest unit, model and UI tests", "Instruction semantics, the five processor models, hazards, caches, Cache Lab, scheduler, profiler, editor and UI (see COVERAGE.md)",
  f"{len(cpp)} files, {n_macros} TEST macros, {n_rows} `.inc` rows; 4,363 registered CTest cases", "`01_unit_tests/` (repo `test/`)",
  "`ctest --test-dir build-tests --output-on-failure` (serial, never `-j`)", "about 10 min (608 s)", "4,363 / 4,363 pass"),
 ("FP oracle self-test", "The IEEE 754 F+D oracle itself agrees with host arithmetic", "20,000 add/mul/div + 5,000 sqrt",
  "`02_.../lib/selftest.py`", "part of `scripts/run_verification.sh`", "2 s", "bad 0, pass (2026-11-24)"),
 ("ISA sweep", "Every swept mnemonic gives the same final state on all 5 models and equals the oracle", "15,328 programs x 5 models",
  "`02_.../isa/`", "part of `scripts/run_verification.sh`", "about 95 s", "0 divergences, 0 mismatches, pass (2026-11-24)"),
 ("Hazard / cycle sweep", "Cycle counts vs the analytic 5-stage model; h-nf/h-f state; rvss vs oracle", "63,056 programs x 5 models",
  "`02_.../hazard/`", "part of `scripts/run_verification.sh`", "about 12.5 min", "0 mismatches, pass (2026-11-24)"),
 ("`li` audit", "Every `li` expansion computes its value", "6,161 values",
  "`02_.../tables/li_audit.py`", "part of `scripts/run_verification.sh`", "about 80 s", "0 wrong, pass (2026-11-24)"),
 ("L1 cache sweep", "Hit/miss/eviction counts vs a textbook cache model", "315 runs (9 programs x 7 configs x 5 models)",
  "`02_.../cache/`", "part of `scripts/run_verification.sh`", "about 40 s", "12 known L2 mismatches (known_issues 130), 0 on L1; pass (2026-11-24)"),
 ("Assembler corpus", "Machine code, tokens and parse errors byte-identical to the recorded result", "58 programs, 174 dumps",
  "`02_.../asm/`", "part of `scripts/run_verification.sh`", "about 6 s", "0 differing, pass (2026-11-24)"),
 ("Committed tables", "The expectation tables under `test/` are what their generators print", f"{len(generated)} tables",
  "`02_.../tables/check_tables.py`", "part of `scripts/run_verification.sh`", "about 1 s", "18 of 18 matching (2026-11-24 run; see note)"),
 ("Negative controls", "Every checker above can fail", "see note",
  "`02_.../negative_controls.py`", "part of `scripts/run_verification.sh`", "about 50 s", "5 of 5 caught (2026-11-24 run; see note)"),
 ("Example programs", "Demo and test programs: hazards, forwarding, F/D, caches, Cache Lab, scheduler, undo/redo", f"{len(ex)} programs/scripts",
  "`03_example_programs/` (repo `examples/`)", "open in Atlas, or used by the unit tests (see INDEX.md)", "-", "no separate record; covered by the tests that use them"),
]
rd = [f"# Atlas verification test cases\n",
 f"A reviewable copy of every test asset of Atlas, the RISC-V teaching simulator, taken with `git archive` "
 f"from commit `{commit}` ({cdate}) by `scripts/make_verification_pack.sh`.\n",
 "**This pack is for reading, not for running on its own.** It contains the test code, the case tables, the "
 "independent checkers and the test programs, but not the simulator. To run anything here you need the Atlas "
 "source: the GitHub repository (branch `main`) or the source ZIP. The folders below map one-to-one to repo "
 "folders, so a file here is at the same relative path in the source.\n",
 "## Contents\n",
 "| Path | What it is |\n| --- | --- |",
 f"| `README.md` | This file. |",
 f"| `COVERAGE.md` | Coverage matrix, generated by the script from test file names and contents (ISA groups, the five models, hazards, branches, caches, Cache Lab, scheduler, profiler, UI). |",
