#!/usr/bin/env python3
"""Stage E6 part 3: the committed subset of the hazard sweep.

One program per consumer mnemonic x source slot at distance 0, fed by a load
(ld for an integer slot, fld for an FP slot: the producer both hazard models
must stall for), plus the FP-store cases E6 fixed (fsw/fsd then a reader of
the f register named by imm[4:0]). Expected consumer values come from
hazgen.oracle (E3's alu(), E5's fpo.py, spec code), cycles from hazgen.cycles
(the pipeline rules) - never from the simulator.
"""
import os, sys
sys.argv = sys.argv[:1]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hazgen as H


def cpp(name, text, exp, cyc_nf, cyc_f):
    xs, fs, ds = [], [], []
    for r, v in sorted(exp.items()):
        v = H.u64(v)
        if r[0] == "x":
            xs.append(f"{{{int(r[1:])}, 0x{v:X}ULL}}")
        elif r[0] == "f":
            fs.append(f"{{{int(r[1:])}, 0x{v:X}ULL}}")
        else:
            ds.append(f"{{0x{H.SCR + 8 * int(r[1:]):X}ULL, 0x{v:X}ULL}}")
    return (f'    {{"{name}", R"ASM({text})ASM", {cyc_nf}u, {cyc_f}u,\n'
            f'     {{{", ".join(xs)}}}, {{{", ".join(fs)}}}, {{{", ".join(ds)}}}}},')


def main():
    out = []
    for cons in H.consumer_slots():
        pname = "ld" if cons[2] == "x" else "fld"
        r = H.build(cons, pname, "same", 0)
        if r is None:
            print(f"no program for {cons}", file=sys.stderr)
            continue
        text, info = r
        exp, taken = H.oracle(info)
        seq = H.executed(info, taken)
        out.append(cpp(f"{cons[0]}.{cons[1]}", text, exp, H.cycles(seq, "h-nf"), H.cycles(seq, "h-f")))
    # the FP-store producer: fsw/fsd with imm[4:0] = 5, then a reader of f5
    for st in ("fsw", "fsd"):
        for cons in (("fadd.s", "rs1", "f", "any", "f"), ("fmadd.d", "rs3", "f", "any", "f"),
                     ("fsw", "rs2", "f", "any", None)):
            r = H.build(cons, st, "same", 0)
            text, info = r
            exp, taken = H.oracle(info)
            seq = H.executed(info, taken)
            out.append(cpp(f"{st}-then-{cons[0]}.{cons[2]}{cons[1]}", text, exp,
                           H.cycles(seq, "h-nf"), H.cycles(seq, "h-f")))
    print("// GENERATED by verification/hazard/gen_subset.py - do not edit by hand.")
    print("const SubsetCase kSubset[] = {")
    print("\n".join(out))
    print("};")
    print(f"{len(out)} programs", file=sys.stderr)


if __name__ == "__main__":
    main()
