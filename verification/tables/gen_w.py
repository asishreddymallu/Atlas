#!/usr/bin/env python3
"""Stage E3 part A (known_issues 109): the base RV64 W instructions.

Prints the C++ tables for test/w_forms_test.cpp:
  kEncoding  - one source line each, with the word an encoder written from
               the spec's field layout (common.r_type / common.i_type) gives;
  kCases     - padded programs, results in x12..x31, values from common.alu.
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
from common import *

R32 = {"addw": (0, 0x00), "subw": (0, 0x20), "sllw": (1, 0x00), "srlw": (5, 0x00), "sraw": (5, 0x20)}
SH32 = {"slliw": (1, 0x00), "srliw": (5, 0x00), "sraiw": (5, 0x20)}

# ---- encoding ----------------------------------------------------------------
enc = []
for mn, (f3, f7) in R32.items():
    for rd, rs1, rs2 in [(5, 6, 7), (0, 31, 1), (31, 31, 31)]:
        enc.append((f"{mn} x{rd}, x{rs1}, x{rs2}", r_type(OPCODE["OP-32"], f3, f7, rd, rs1, rs2)))
for rd, rs1, imm in [(5, 6, 0), (31, 1, -1), (0, 2, 2047), (7, 7, -2048), (9, 8, 1)]:
    enc.append((f"addiw x{rd}, x{rs1}, {imm}", i_type(OPCODE["OP-IMM-32"], 0, rd, rs1, imm)))
for mn, (f3, f7) in SH32.items():
    for rd, rs1, sh in [(5, 6, 0), (31, 1, 31), (6, 6, 17)]:
        enc.append((f"{mn} x{rd}, x{rs1}, {sh}", r_type(OPCODE["OP-IMM-32"], f3, f7, rd, rs1, sh)))

# ---- execution ---------------------------------------------------------------
V = [0, 1, u64(-1), (1 << 31) - 1, u64(-(1 << 31)), 1 << 31, 0xFFFFFFFF, 1 << 63]
VN = ["0", "1", "-1", "INT32_MAX", "INT32_MIN", "0x80000000", "0xFFFFFFFF", "INT64_MIN"]
cases = []


def chunked(name, ops):
    """ops: list of (asm-with-{rd}, a, b, expected); 20 per program, rd x12..x31."""
    for n in range(0, len(ops), 20):
        p, x = Program(), {}
        for k, (line, a, b, exp) in enumerate(ops[n:n + 20]):
            rd = 12 + k
            if a is not None:
                p.load("x6", a)
            if b is not None:
                p.load("x7", b)
            p.ins(line.format(rd=f"x{rd}"))
            x[rd] = exp
        cases.append(cpp_case(f"{name}{n // 20}", p.text(), x=x))


for mn in R32:
    if mn in ("sllw", "srlw", "sraw"):
        ops = [(f"{mn} {{rd}}, x6, x7", a, c, alu(mn, a, c)) for a in V for c in (0, 31, 32, 63)]
    else:
        ops = [(f"{mn} {{rd}}, x6, x7", a, b, alu(mn, a, b)) for a in V for b in V]
    chunked(mn, ops)
chunked("addiw", [(f"addiw {{rd}}, x6, {imm}", a, None, alu("addiw", a, u64(imm)))
                  for a in V for imm in (0, 1, -1, 2047, -2048)])
for mn in SH32:
    chunked(mn, [(f"{mn} {{rd}}, x6, {sh}", a, None, alu(mn, a, sh)) for a in V for sh in (0, 31)])

# rd = x0 and rs1 = rd, one program per mnemonic
for mn in list(R32) + ["addiw"] + list(SH32):
    p = Program()
    a, b = u64(-1), (1 << 31) - 1
    p.load("x6", a)
    p.load("x7", b)
    second = "x7" if mn in R32 else ("5" if mn in SH32 else "-3")
    bval = b if mn in R32 else (5 if mn in SH32 else u64(-3))
    p.ins(f"{mn} x0, x6, {second}", f"{mn} x6, x6, {second}")
    cases.append(cpp_case(f"{mn}RdX0AndRs1EqRd", p.text(), x={0: 0, 6: alu(mn, a, bval)}))

# regression: what already worked must still work
for mn in ("mulw", "divw", "divuw", "remw", "remuw"):
    chunked(f"{mn}Regression", [(f"{mn} {{rd}}, x6, x7", a, b, alu(mn, a, b))
                                for a in V for b in (0, 1, u64(-1), u64(-(1 << 31)), 7)])
for mn in ("negw", "sext.w"):
    chunked(f"{mn.replace('.', '')}Regression", [(f"{mn} {{rd}}, x6", a, None, alu(mn, a, 0)) for a in V])

print("// GENERATED by verification/tables/gen_w.py - do not edit by hand.")
print("const EncodingCase kEncoding[] = {")
for line, word in enc:
    print(f'    {{"{line}", 0x{word:08X}u}},')
print("};")
print("const IsaCase kCases[] = {")
print("\n".join(cases))
print("};")
print(f"// {len(enc)} encodings, {len(cases)} programs", file=sys.stderr)
