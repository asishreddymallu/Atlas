#!/usr/bin/env python3
"""Regenerates every expectation table committed under test/ and checks that
the committed copy is exactly what the generator prints today.

The generators compute expected values from the RISC-V spec, IEEE 754 and
textbook models, never from the simulator. This check proves the committed
tables are reproducible from them (and that nobody edited a table by hand).

Comparison: comment-only lines are ignored (the "GENERATED by" header names
the script's old location in some files, and one generator's closing note was
not pasted), leading/trailing spaces are ignored, and each
blank-line-separated block of the output must appear as a contiguous run of
lines in the target file.

Needs, before it runs: `isa/sweep.py lists` (for gen_tables.py) and
`tables/li_audit.py values` (for gen_li.py). Prints one line per table and
"tables N, matching M"; exits 1 if any differs.
"""
import os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
VERIFY = os.path.dirname(HERE)
ROOT = os.path.dirname(VERIFY)

TABLES = [  # (generator, committed file)
    ("cache/gen_cases.py", "test/cache_lab_cases.inc"),
    ("timing/gen_timing.py", "test/timing_cases.inc"),
    ("timing/gen_hdu.py", "test/hdu_false_stall_test.cpp"),
    ("hazard/gen_tables.py", "test/hazard_tables_test.cpp"),
    ("hazard/gen_subset.py", "test/hazard_sweep_subset_test.cpp"),
    ("tables/gen_call.py", "test/call_tail_test.cpp"),
    ("tables/gen_csr.py", "test/csr_test.cpp"),
    ("tables/gen_csr_pseudo.py", "test/csr_pseudo_test.cpp"),
    ("tables/gen_dflags.py", "test/double_flags_test.cpp"),
    ("tables/gen_dround.py", "test/double_rounding_test.cpp"),
    ("tables/gen_fclass.py", "test/fclass_test.cpp"),
    ("tables/gen_fcvt_int.py", "test/fp_to_int_test.cpp"),
    ("tables/gen_fdiv.py", "test/fdiv_zero_test.cpp"),
    ("tables/gen_fflags.py", "test/fflags_test.cpp"),
    ("tables/gen_li.py", "test/li_expansion_test.cpp"),
    ("tables/gen_pcrel.py", "test/pc_relative_test.cpp"),
    ("tables/gen_shift.py", "test/shift_immediate_test.cpp"),
    ("tables/gen_w.py", "test/w_forms_test.cpp"),
]


def norm(text):
    return [l.strip() for l in text.splitlines() if not l.strip().startswith("//")]


def blocks(lines):
    cur = []
    for l in lines:
        if l:
            cur.append(l)
        elif cur:
            yield cur
            cur = []
    if cur:
        yield cur


def contains(hay, needle):
    n = len(needle)
    first = needle[0]
    for i, l in enumerate(hay):
        if l == first and hay[i:i + n] == needle:
            return True
    return False


def check(gen, target):
    r = subprocess.run([sys.executable, os.path.join(VERIFY, gen)], capture_output=True, text=True,
                       cwd=os.path.dirname(os.path.join(VERIFY, gen)))
    if r.returncode != 0:
        return "ERROR", r.stderr.strip().splitlines()[-1:] or ["exit %d" % r.returncode]
    hay = [l for l in norm(open(os.path.join(ROOT, target)).read()) if l]
    missing = [b for b in blocks(norm(r.stdout)) if not contains(hay, b)]
    if not missing:
        return "MATCH", []
    return "DIFF", [f"{len(missing)} block(s) not found, first starts: {missing[0][0][:70]}"]


def main():
    ok = 0
    for gen, target in TABLES:
        verdict, why = check(gen, target)
        ok += verdict == "MATCH"
        print(f"{verdict:5}  {gen:28} -> {target}" + (f"  ({why[0]})" if why else ""))
    print(f"tables {len(TABLES)}, matching {ok}")
    sys.exit(0 if ok == len(TABLES) else 1)


if __name__ == "__main__":
    main()
