#!/usr/bin/env python3
"""Stage E5 update of E4's DoubleFlags (known_issues 108, now 72's semantics).

Same eleven double ops on the same inputs. fflags is cleared before each op
(csrwi fflags, 0) and read after it, so each word is exactly the flags that op
raised, in RISC-V's layout (NX 0, UF 1, OF 2, DZ 3, NV 4), from fpo.py.
E4 set 31 first and expected 72's replacing bool; under accrual that would
read 31 after every op and test nothing.
"""
import os, struct, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
from common import Program, cpp_case, SCRATCH
from fpo import *

D = lambda x: struct.unpack("<Q", struct.pack("<d", x))[0]
OPS = [("fdiv.d", 1.0, 3.0), ("fdiv.d", 1.0, 4.0), ("fdiv.d", 1.0, 0.0), ("fadd.d", 1.0, 2.0 ** -60),
       ("fadd.d", 1.0, 2.0), ("fmul.d", 3.0, 0.5), ("fmul.d", 0.1, 0.1), ("fsqrt.d", 2.0, None),
       ("fsqrt.d", 4.0, None), ("fsqrt.d", -1.0, None), ("fsub.d", 1e308, -1e308)]
FN = {"fdiv.d": lambda a, b: div(F64, a, b, RNE), "fadd.d": lambda a, b: add(F64, a, b, RNE),
      "fmul.d": lambda a, b: mul(F64, a, b, RNE), "fsub.d": lambda a, b: add(F64, a, b, RNE, neg_b=True),
      "fsqrt.d": lambda a, b: sqrt(F64, a, RNE)}
p, dw = Program(), {}
for k, (mn, a, b) in enumerate(OPS):
    p.ins(f"fld f1, {p.value(D(a))}(x10)")
    if b is not None:
        p.ins(f"fld f2, {p.value(D(b))}(x10)")
    p.ins("csrwi fflags, 0", f"{mn} f3, f1" + (", f2" if b is not None else ""), "csrr x5, fflags",
          f"sd x5, {8 * k}(x11)")
    dw[SCRATCH + 8 * k] = FN[mn](D(a), D(b) if b is not None else 0)[1]
print("// GENERATED by verification/tables/gen_dflags.py - do not edit by hand.")
print("const IsaCase kCases[] = {")
print(cpp_case("DoubleOpsWriteFflags", p.text(), dwords=dw))
print("};")
print(list(dw.values()), file=sys.stderr)
