#!/usr/bin/env python3
"""Stage E3 part C (known_issues 106): every shift-immediate at every legal
shamt. One program per (mnemonic, input); each result is stored to scratch
memory at SCRATCH + 8*shamt. Values from common.alu (the Python oracle)."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
from common import *

INPUTS = [("Msb1Lsb1", 0x8000000000000001), ("AllOnes", u64(-1)), ("Bit31Block", 0x00000000F0000000)]
cases = []
for mn, top in [("slli", 63), ("srli", 63), ("srai", 63), ("slliw", 31), ("srliw", 31), ("sraiw", 31)]:
    for tag, a in INPUTS:
        p, mem = Program(), {}
        p.load("x6", a)
        for sh in range(top + 1):
            p.ins(f"{mn} x5, x6, {sh}", f"sd x5, {8 * sh}(x11)")
            mem[SCRATCH + 8 * sh] = alu(mn, a, sh)
        cases.append(cpp_case(f"{mn}{tag}", p.text(), dwords=mem))
print("// GENERATED by verification/tables/gen_shift.py - do not edit by hand.")
print("const IsaCase kCases[] = {")
print("\n".join(cases))
print("};")
print(len(cases), "programs", file=sys.stderr)
