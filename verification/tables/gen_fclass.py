#!/usr/bin/env python3
"""Stage E4 part 3 (known_issues 52): fclass.s / fclass.d.

The spec's 10-bit mask (RISC-V F, Table "Format of result of FCLASS"):
bit 0 -inf, 1 negative normal, 2 negative subnormal, 3 -0, 4 +0,
5 positive subnormal, 6 positive normal, 7 +inf, 8 signaling NaN,
9 quiet NaN. The class of each bit pattern is computed here from its
fields, not from any float library. Plus encodings by field layout.
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
from common import *


def fclass(bits, w):
    eb, fb = (8, 23) if w == 32 else (11, 52)
    sign = bits >> (w - 1) & 1
    exp = bits >> fb & ((1 << eb) - 1)
    frac = bits & ((1 << fb) - 1)
    emax = (1 << eb) - 1
    if exp == emax:
        if frac == 0:
            return 1 << (0 if sign else 7)
        return 1 << (9 if frac >> (fb - 1) else 8)
    if exp == 0:
        if frac == 0:
            return 1 << (3 if sign else 4)
        return 1 << (2 if sign else 5)
    return 1 << (1 if sign else 6)


S = [0xFF800000, 0xBF800000, 0x80000001, 0x807FFFFF, 0x80000000, 0x00000000, 0x00000001,
     0x007FFFFF, 0x3F800000, 0x7F7FFFFF, 0x7F800000, 0x7F800001, 0x7FBFFFFF, 0x7FC00000,
     0xFFC00000, 0xFF800001, 0x00800000, 0x80800000]
D = [0xFFF0000000000000, 0xBFF0000000000000, 0x8000000000000001, 0x800FFFFFFFFFFFFF,
     1 << 63, 0, 1, 0x000FFFFFFFFFFFFF, 0x3FF0000000000000, 0x7FEFFFFFFFFFFFFF,
     0x7FF0000000000000, 0x7FF0000000000001, 0x7FF7FFFFFFFFFFFF, 0x7FF8000000000000,
     0xFFF8000000000000, 0xFFF0000000000001, 0x0010000000000000, 0x8010000000000000]

cases = []
for w, vals, mn, ld in ((32, S, "fclass.s", "flw"), (64, D, "fclass.d", "fld")):
    p, dw = Program(), {}
    for k, b in enumerate(vals):
        p.ins(f"{ld} f1, {p.value(b)}(x10)", f"{mn} x5, f1", f"sd x5, {8 * k}(x11)")
        dw[SCRATCH + 8 * k] = fclass(b, w)
    seen = {fclass(b, w).bit_length() - 1 for b in vals}
    assert seen == set(range(10)), seen
    cases.append(cpp_case(f"{mn.replace('.', '_')}_AllTenClasses", p.text(), dwords=dw))
    # rd = x0 is not written; f-register index 31 and rd 31 encode
    p = Program()
    p.ins(f"{ld} f31, {p.value(vals[13])}(x10)", f"{mn} x31, f31", f"{mn} x0, f31")
    cases.append(cpp_case(f"{mn.replace('.', '_')}_Regs31AndX0", p.text(), x={31: 1 << 9, 0: 0}))

enc = []
for mn, f7 in (("fclass.s", 0b1110000), ("fclass.d", 0b1110001)):
    for rd, rs1 in ((5, 1), (0, 31), (31, 0)):
        word = (f7 << 25) | (0 << 20) | (rs1 << 15) | (0b001 << 12) | (rd << 7) | 0b1010011
        enc.append(f'    {{"{mn} x{rd}, f{rs1}", 0x{word:08X}u}},')
print("// GENERATED by verification/tables/gen_fclass.py - do not edit by hand.")
print("const IsaCase kCases[] = {")
print("\n".join(cases))
print("};")
print("const struct { const char *line; uint32_t word; } kEncodings[] = {")
print("\n".join(enc))
print("};")
