#!/usr/bin/env python3
"""Stage E3 part E (known_issues 111): call and tail.

call f = jal ra, f; tail f = jal x0, f (the user's choice: one instruction,
+-1 MiB). One padded program; every link value and landing is computed from
the layout (address = 4 * instruction index), not from the simulator.

    j main
  back:   addi x26, 26; ret                 <- called backward
  main:   call f        (x1 = link1)
          mv x27, x1                         x27 = link of `call f`... restored by f
          call back     (backward)
          addi x21, 21
          tail h        (top level: no link)
          addi x22, 22                       skipped
  f:      addi x20, 20
          mv x8, x1                          save ra
          call g
          mv x9, x1                          x9 = link of `call g` (g tail-called k,
          mv x1, x8                                 whose ret came back here)
          ret
  g:      addi x23, 23
          tail k                             tail out of a called function
          addi x28, 28                       skipped
  k:      addi x24, 24
          ret                                returns to g's caller (f)
  h:      addi x25, 25
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
from common import *

lines, labels = [], {}


def ins(*xs):
    for x in xs:
        lines.append(("i", x))
        for g in GAP:
            lines.append(("i", g))


def label(n):
    labels[n] = sum(1 for k, _ in lines if k == "i")
    lines.append(("l", n))


def index_of(text):
    """Index of the first instruction whose text is `text`."""
    n = 0
    for k, x in lines:
        if k == "i":
            if x == text:
                return n
            n += 1
    raise KeyError(text)


ins("j main")
label("back"); ins("addi x26, x0, 26", "ret")
label("main")
ins("call f", "mv x27, x1", "call back", "addi x21, x0, 21", "tail h", "addi x22, x0, 22")
label("f"); ins("addi x20, x0, 20", "mv x8, x1", "call g", "mv x9, x1", "mv x1, x8", "ret")
label("g"); ins("addi x23, x0, 23", "tail k", "addi x28, x0, 28")
label("k"); ins("addi x24, x0, 24", "ret")
label("h"); ins("addi x25, x0, 25")

link = lambda t: 4 * (index_of(t) + 1)
expect = {
    8: link("call f"),        # f saved its own return address
    9: link("call g"),        # k's ret came back into f, after `call g`
    27: link("call f"),       # after f returned, x1 was f's link again
    1: link("call back"),     # the last link written before the tail
    20: 20, 21: 21, 22: 0, 23: 23, 24: 24, 25: 25, 26: 26, 28: 0,
}
text = ".text\n" + "\n".join(f"{x}:" if k == "l" else f"    {x}" for k, x in lines) + "\n"
print("// GENERATED by verification/tables/gen_call.py - do not edit by hand.")
print("const IsaCase kCases[] = {")
print(cpp_case("CallTailNestedBackward", text, x=expect))
print("};")
