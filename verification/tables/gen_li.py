#!/usr/bin/env python3
"""Stage E3 part B (known_issues 110): the table for test/li_expansion_test.cpp.

Values: the +-2^11, 2^31, 2^32 and 2^63 boundaries, 0x7FFFF800 and
0x7FFFFFFF, every 128th value between them, their negatives, and 32 seeded
random 64-bit values. Expected register value = the value (mod 2^64).
Expected instruction count = the count the PRE-FIX assembler emitted
(words-before.txt from li_audit.py), so the fix cannot change the length of
any expansion."""
import json, os, random, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
from common import u64, s64
import vpaths
# values.json is regenerated by `li_audit.py values` (seeded); the pre-fix
# words are a pinned record of the assembler before the fix (tables/data).
allv = json.load(open(vpaths.out("li", "values.json")))
count = {}
for line in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "li_words_before.txt")):
    p = line.split()
    count[allv[int(p[0])]] = len(p) - 2
vals = set()
for c in (1 << 11, 1 << 31, 1 << 32, 1 << 63):
    for d in (-1, 0, 1):
        vals.add(u64(c + d)); vals.add(u64(-(c + d)))
for x in list(range(0x7FFFF800, 0x80000000, 128)) + [0x7FFFFFFF, 0x7FFFFFFE]:
    vals.add(x); vals.add(u64(-x))
rng = random.Random(20261119)
vals |= set(rng.sample([v for v in allv if v >> 32 not in (0, 0xFFFFFFFF)], 32))
vals = sorted(vals)
assert all(v in count for v in vals)
print("// GENERATED by verification/tables/gen_li.py - do not edit by hand.")
print("const LiCase kLi[] = {")
for v in vals:
    lit = str(s64(v)) if s64(v) < 0 else hex(v)
    print(f'    {{"{lit}", 0x{v:016X}ULL, {count[v]}u}},')
print("};")
print(len(vals), "values", file=sys.stderr)
