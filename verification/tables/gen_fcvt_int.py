#!/usr/bin/env python3
"""Stage E4 part 2 (known_issues 73): fcvt.{w,wu,l,lu}.{s,d}.

Oracle from the RISC-V F/D spec (fcvt to integer): round the exact value
in the instruction's mode; NaN and +inf give the largest value of the type,
-inf the smallest (0 for unsigned); a rounded value outside the type
saturates to the nearer bound (a negative value to an unsigned type gives
0); 32-bit results are sign-extended to 64 bits. RMM (113, open) is
asserted only off ties. Flags are not asserted (72, open).

One program per (mnemonic, mode): each input is loaded, converted to x5 and
stored as a dword to scratch, padded.
"""
import math, os, struct, sys
from fractions import Fraction
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
from common import *

f2b = lambda x: struct.unpack("<I", struct.pack("<f", x))[0]
d2b = lambda x: struct.unpack("<Q", struct.pack("<d", x))[0]
b2f = lambda b: struct.unpack("<f", struct.pack("<I", b))[0]
b2d = lambda b: struct.unpack("<d", struct.pack("<Q", b))[0]
nf = lambda x, d: b2f(f2b(x) + (1 if (x > 0) == (d > 0) else -1)) if x != 0 else None
TYPES = {"w": (-(1 << 31), (1 << 31) - 1, True), "wu": (0, (1 << 32) - 1, True),
         "l": (-(1 << 63), (1 << 63) - 1, False), "lu": (0, (1 << 64) - 1, False)}


def rnd(q, mode):
    f = math.floor(q); fr = q - f
    if mode == "rtz": return math.trunc(q)
    if mode == "rdn": return f
    if mode == "rup": return math.ceil(q)
    if mode == "rmm":
        if fr == Fraction(1, 2): return f + 1 if q > 0 else f
        return f if fr < Fraction(1, 2) else f + 1
    return round(q)


def cvt(bits, fmt, t, mode):
    lo, hi, is32 = TYPES[t]
    x = b2f(bits) if fmt == "s" else b2d(bits)
    if math.isnan(x): r = hi
    elif math.isinf(x): r = hi if x > 0 else lo
    else:
        r = rnd(Fraction(x), mode)
        r = min(max(r, lo), hi)
    return u64(sx(r, 32)) if is32 else u64(r)


def is_tie(bits, fmt):
    x = b2f(bits) if fmt == "s" else b2d(bits)
    if not math.isfinite(x): return False
    q = Fraction(x)
    return q - math.floor(q) == Fraction(1, 2)


def around(v, fmt):
    """v and its two neighbours in the format (v must be representable)."""
    if fmt == "s":
        b = f2b(v)
        return [b - 1 if v > 0 else b + 1, b, b + 1 if v > 0 else b - 1] if v != 0 else [b]
    b = d2b(v)
    return [b - 1 if v > 0 else b + 1, b, b + 1 if v > 0 else b - 1] if v != 0 else [b]


def inputs(fmt):
    enc = f2b if fmt == "s" else d2b
    out = []
    if fmt == "s":
        out += [0x7FC00000, 0x7F800001, 0xFFC00000, 0x7F800000, 0xFF800000]
    else:
        out += [0x7FF8000000000000, 0x7FF0000000000001, 0xFFF8000000000000,
                0x7FF0000000000000, 0xFFF0000000000000]
    for p in (2.0 ** 31, -(2.0 ** 31), 2.0 ** 32, 2.0 ** 63, -(2.0 ** 63), 2.0 ** 64):
        out += around(p, fmt)
    for v in (0.0, -0.0, 0.4, -0.4, 0.5, -0.5, 1.5, -1.5, 2.5, -2.5, -1.0, 3.7, -3.7):
        out.append(enc(v))
    if fmt == "d":
        for v in (2147483647.5, 2147483647.4, -2147483648.5, -2147483648.4, 4294967295.5,
                  4294967295.4, 9007199254740993.0 * 1024):
            out.append(enc(v))
    seen = []
    for b in out:
        if b not in seen: seen.append(b)
    return seen


cases, total = [], 0
for fmt in ("s", "d"):
    ins = inputs(fmt)
    for t in ("w", "wu", "l", "lu"):
        mn = f"fcvt.{t}.{fmt}"
        for mode in ("rne", "rtz", "rdn", "rup", "rmm"):
            p, dw = Program(), {}
            for k, b in enumerate([b for b in ins if not (mode == "rmm" and is_tie(b, fmt))]):
                ld = "flw" if fmt == "s" else "fld"
                p.ins(f"{ld} f1, {p.value(b)}(x10)", f"{mn} x5, f1, {mode}", f"sd x5, {8 * k}(x11)")
                dw[SCRATCH + 8 * k] = cvt(b, fmt, t, mode)
            total += len(dw)
            cases.append(cpp_case(f"{mn.replace('.', '_')}_{mode}", p.text(), dwords=dw))
print("// GENERATED by verification/tables/gen_fcvt_int.py - do not edit by hand.")
print("const IsaCase kCases[] = {")
print("\n".join(cases))
print("};")
print(len(cases), "programs,", total, "conversions", file=sys.stderr)
