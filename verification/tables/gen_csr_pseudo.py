#!/usr/bin/env python3
"""Stage E4 part 4b (104): the standard Zicsr pseudo-instructions.

From the spec's pseudo-instruction table:
  csrr rd, csr     = csrrs rd, csr, x0      csrw csr, rs   = csrrw x0, csr, rs
  csrs csr, rs     = csrrs x0, csr, rs      csrc csr, rs   = csrrc x0, csr, rs
  csrwi csr, imm   = csrrwi x0, csr, imm    csrsi csr, imm = csrrsi x0, csr, imm
  csrci csr, imm   = csrrci x0, csr, imm
Encodings by field layout; one execution program checked against the fcsr
model (fflags = fcsr[4:0], frm = fcsr[7:5]).
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
from common import *

ADDR = {"fflags": 1, "frm": 2, "fcsr": 3}
F3 = {"csrrw": 1, "csrrs": 2, "csrrc": 3, "csrrwi": 5, "csrrsi": 6, "csrrci": 7}


def word(base, rd, csr, rs1):
    return (ADDR[csr] << 20) | (rs1 << 15) | (F3[base] << 12) | (rd << 7) | 0b1110011


enc = []
for csr in ("fflags", "frm", "fcsr"):
    enc += [(f"csrr x5, {csr}", word("csrrs", 5, csr, 0)),
            (f"csrw {csr}, x6", word("csrrw", 0, csr, 6)),
            (f"csrs {csr}, x7", word("csrrs", 0, csr, 7)),
            (f"csrc {csr}, x31", word("csrrc", 0, csr, 31)),
            (f"csrwi {csr}, 21", word("csrrwi", 0, csr, 21)),
            (f"csrsi {csr}, 31", word("csrrsi", 0, csr, 31)),
            (f"csrci {csr}, 1", word("csrrci", 0, csr, 1))]


class M:
    v = 0
    def r(self, c): return {1: self.v & 31, 2: (self.v >> 5) & 7, 3: self.v & 0xFF}[ADDR[c]]
    def w(self, c, x):
        a = ADDR[c]
        if a == 1: self.v = (self.v & ~31) | (x & 31)
        elif a == 2: self.v = (self.v & ~0xE0) | ((x & 7) << 5)
        else: self.v = x & 0xFF


m, p, dw, k = M(), Program(), {}, 0
x = {6: 0xC3, 7: 0x14, 8: 0x7}
for r, v in x.items(): p.load(f"x{r}", v)


def rd_all():
    global k
    for c in ("fflags", "frm", "fcsr"):
        p.ins(f"csrr x5, {c}", f"sd x5, {8 * k}(x11)"); dw[SCRATCH + 8 * k] = m.r(c); k += 1


steps = [("csrw fcsr, x6", lambda: m.w("fcsr", x[6])), ("csrs fflags, x7", lambda: m.w("fflags", m.r("fflags") | x[7])),
         ("csrc fcsr, x8", lambda: m.w("fcsr", m.r("fcsr") & ~x[8])), ("csrwi frm, 5", lambda: m.w("frm", 5)),
         ("csrsi fflags, 3", lambda: m.w("fflags", m.r("fflags") | 3)), ("csrci fcsr, 16", lambda: m.w("fcsr", m.r("fcsr") & ~0x10)),
         ("csrw frm, x7", lambda: m.w("frm", x[7])), ("csrci frm, 0", lambda: None), ("csrs fcsr, x0", lambda: None)]
rd_all()
for text, f in steps:
    p.ins(text); f(); rd_all()
print("// GENERATED by verification/tables/gen_csr_pseudo.py - do not edit by hand.")
print("const IsaCase kCases[] = {")
print(cpp_case("AllSevenOnFcsr", p.text(), dwords=dw))
print("};")
print("const struct { const char *line; uint32_t word; } kEncodings[] = {")
for line, w in enc:
    print(f'    {{"{line}", 0x{w:08X}u}},')
print("};")
