#!/usr/bin/env python3
"""Stage E4 part 1 (known_issues 75): fdiv.s / fdiv.d by zero and friends.

Oracle written from IEEE 754 / RISC-V F/D: x/(+-0) = +-inf for finite
non-zero x (sign = XOR), 0/0 and inf/inf = the canonical NaN, any NaN
operand = the canonical NaN, inf/x = +-inf, x/inf = +-0. Singles live
zero-extended in the f register (known_issues 71). Flags are not asserted
(72 open).
"""
import os, struct, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
from common import *

CAN32, CAN64 = 0x7FC00000, 0x7FF8000000000000
INF32, INF64 = 0x7F800000, 0x7FF0000000000000


def fdiv(a, b, w):
    """a, b are bit patterns of width w (32/64). Returns the result bits."""
    sbit = 1 << (w - 1)
    expm = 0xFF << 23 if w == 32 else 0x7FF << 52
    fracm = (1 << 23) - 1 if w == 32 else (1 << 52) - 1
    inf, can = (INF32, CAN32) if w == 32 else (INF64, CAN64)
    isnan = lambda x: (x & expm) == expm and (x & fracm)
    isinf = lambda x: (x & ~sbit) == inf
    iszero = lambda x: (x & ~sbit) == 0
    sign = (a ^ b) & sbit
    if isnan(a) or isnan(b):
        return can
    if (iszero(a) and iszero(b)) or (isinf(a) and isinf(b)):
        return can
    if isinf(a) or iszero(b):
        return sign | inf
    if iszero(a) or isinf(b):
        return sign
    # finite / finite non-zero: use the host's correctly rounded division (RNE)
    if w == 64:
        fa, fb = (struct.unpack("<d", struct.pack("<Q", x))[0] for x in (a, b))
        return struct.unpack("<Q", struct.pack("<d", fa / fb))[0]
    from fractions import Fraction
    fa, fb = (struct.unpack("<f", struct.pack("<I", x))[0] for x in (a, b))
    q = Fraction(fa) / Fraction(fb)
    d = float(q)  # exact enough: double rounding of a quotient is innocuous
    return struct.unpack("<I", struct.pack("<f", d))[0]


S = {"p1": 0x3F800000, "m1": 0xBF800000, "p0": 0, "m0": 0x80000000, "pinf": INF32,
     "minf": 0xFF800000, "qnan": 0x7FC00001, "snan": 0x7F800001, "nnan": 0xFFC00000,
     "psub": 0x00000001, "msub": 0x80000001, "big": 0x7F7FFFFF, "p3": 0x40400000}
D = {"p1": 0x3FF0000000000000, "m1": 0xBFF0000000000000, "p0": 0, "m0": 1 << 63,
     "pinf": INF64, "minf": 0xFFF0000000000000, "qnan": 0x7FF8000000000001,
     "snan": 0x7FF0000000000001, "nnan": 0xFFF8000000000000, "psub": 1, "msub": (1 << 63) | 1,
     "big": 0x7FEFFFFFFFFFFFFF, "p3": 0x4008000000000000}
PAIRS = [("p1", "p0"), ("p1", "m0"), ("m1", "p0"), ("m1", "m0"), ("p0", "p0"), ("m0", "p0"),
         ("p0", "m0"), ("pinf", "pinf"), ("minf", "pinf"), ("pinf", "p0"), ("minf", "m0"),
         ("qnan", "p0"), ("snan", "p1"), ("p1", "nnan"), ("psub", "p0"), ("msub", "p0"),
         ("big", "p0"), ("p0", "p3"), ("m0", "p3"), ("psub", "pinf"), ("p1", "p3"),
         ("p0", "psub"), ("psub", "psub")]

cases = []
for w, tab, mn, ld in ((32, S, "fdiv.s", "flw"), (64, D, "fdiv.d", "fld")):
    for a, b in PAIRS:
        p = Program()
        p.ins(f"{ld} f1, {p.value(tab[a])}(x10)", f"{ld} f2, {p.value(tab[b])}(x10)",
              f"{mn} f3, f1, f2")
        cases.append(cpp_case(f"{mn.replace('.', '_')}_{a}_by_{b}", p.text(),
                              f={3: fdiv(tab[a], tab[b], w)}))
print("// GENERATED by verification/tables/gen_fdiv.py - do not edit by hand.")
print("const IsaCase kCases[] = {")
print("\n".join(cases))
print("};")
print(len(cases), "cases", file=sys.stderr)
