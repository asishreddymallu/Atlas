#!/usr/bin/env python3
"""Stage E5 part 2 (known_issues 78, 105): the hazard unit's false stalls.

Cycle counts come from the 5-stage pipeline rules, not from the simulator:
  - instruction i reaches ID at t_i; with no hazard t_i = t_{i-1} + 1, the
    first at cycle 2 (IF at 1); the run ends when the last one leaves WB,
    so cycles = t_last + 3 (N + 4 with no hazards, as rv5s_control_flow_test
    asserts);
  - jal resolves in EX: the target reaches ID 3 cycles after the jal (2
    bubbles);
  - no forwarding (h_nf): a consumer reads the register file in ID, which a
    producer writes in WB (first half), so t_c >= t_p + 3;
  - forwarding (h_f): only a load's result is late; t_c >= t_load + 2.
A dependency exists only when the consumer really READS a register of the
same file that the producer really WRITES (x0 never counts). Those read and
write sets are written here from the spec, per mnemonic.
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
from common import DATA, u64

LOADS = {"ld", "fld", "flw"}


def regs(line):
    """(mnemonic, writes {(file, n)}, reads {(file, n)}) from the spec."""
    mn, _, rest = line.partition(" ")
    ops = [o.strip() for o in rest.replace("(", ",").replace(")", "").split(",") if o.strip()]
    r = lambda o: ("x", int(o[1:])) if o[0] == "x" else ("f", int(o[1:]))
    if mn == "nop":
        return mn, set(), set()
    if mn in ("lui", "auipc"):
        return mn, {r(ops[0])}, set()
    if mn == "jal":
        return mn, {r(ops[0])}, set()
    if mn in ("addi", "ld", "fld", "flw", "fcvt.d.l"):
        return mn, {r(ops[0])}, {r(ops[2] if mn in LOADS else ops[1])}
    if mn in ("sd", "fsd", "fsw"):
        return mn, set(), {r(ops[0]), r(ops[2])}
    if mn in ("fadd.d", "fadd.s", "add"):
        return mn, {r(ops[0])}, {r(ops[1]), r(ops[2])}
    raise ValueError(line)


def cycles(lines, forwarding):
    """lines: the executed instruction stream (a jal's skipped instruction is
    not in it; the jal itself carries the bubbles)."""
    t, last = [], 0
    info = [regs(l) for l in lines]
    for i, (mn, w, rd) in enumerate(info):
        ti = 2 if i == 0 else t[-1] + 1
        if i and info[i - 1][0] == "jal":
            ti = t[-1] + 3
        for j in range(i):
            pmn, pw, _ = info[j]
            dep = {x for x in pw & rd if x != ("x", 0)}
            if not dep:
                continue
            if forwarding:
                if pmn in LOADS:
                    ti = max(ti, t[j] + 2)
            else:
                ti = max(ti, t[j] + 3)
        t.append(ti)
    return t[-1] + 3


SETUP = ["lui x10, 0x10000", "ld x5, 0(x10)", "ld x8, 8(x10)", "fld f5, 16(x10)", "fld f7, 24(x10)",
         "flw f1, 32(x10)", "nop", "nop", "nop"]
DATA_WORDS = [41, 77, 0x4000000000000000, 0x3FF0000000000000, 0x40400000]   # 41, 77, 2.0, 1.0, 3.0f
TAIL = ["nop", "nop", "nop", "nop", "sd x6, 64(x10)", "sd x9, 72(x10)"]

# (name, body, skipped-by-jal or None, expected x6, expected x9, whether it is a true dependency)
CASES = [
    ("LoadThenUse", ["ld x5, 0(x10)", "addi x6, x5, 1"], 42, 0, True),
    ("FldThenIntegerIndex", ["fld f5, 16(x10)", "addi x6, x5, 1"], 42, 0, False),
    ("LdThenFpIndex", ["ld x5, 0(x10)", "fadd.d f6, f5, f7", "addi x6, x0, 6"], 6, 0, False),
    ("LdThenLui", ["ld x5, 0(x10)", "lui x6, 0x28"], 0x28000, 0, False),
    ("LdThenAuipc", ["ld x5, 0(x10)", "auipc x6, 0x28"], None, 0, False),
    ("LdThenJal", ["ld x8, 8(x10)", "jal x0, 8", "addi x9, x0, 9", "addi x6, x0, 6"], 6, 0, False),
    ("FlwThenFpUse", ["flw f5, 32(x10)", "fadd.s f6, f5, f1", "addi x6, x0, 6"], 6, 0, True),
    ("AluThenLui", ["addi x5, x0, 5", "lui x6, 0x28"], 0x28000, 0, False),
    ("FpAluThenIntegerIndex", ["fadd.d f5, f5, f7", "addi x6, x5, 1"], 42, 0, False),
]


def program(body):
    lines = SETUP + body + TAIL
    text = ".data\nvals: .dword " + ", ".join(hex(v) for v in DATA_WORDS) + "\n.text\n"
    text += "".join(f"    {l}\n" for l in lines)
    executed = [l for l in lines if l != "addi x9, x0, 9"]
    return text, lines, executed


def main():
    print("// GENERATED by verification/timing/gen_hdu.py - do not edit by hand.")
    print("const HduCase kHduCases[] = {")
    for name, body, x6, x9, true_dep in CASES:
        text, lines, executed = program(body)
        nf, f = cycles(executed, False), cycles(executed, True)
        if x6 is None:   # auipc: pc-relative, pc = 4 * index
            x6 = 4 * lines.index("auipc x6, 0x28") + (0x28 << 12)
        # the no-dependency twin: rename the producer's destination so no index matches
        print(f'    {{"{name}", R"ASM({text})ASM", {nf}u, {f}u, 0x{u64(x6):X}ULL, 0x{x9:X}ULL}},')
        print(f"{name}: h_nf {nf}, h_f {f}, true dependency {true_dep}", file=sys.stderr)
    print("};")


if __name__ == "__main__":
    main()
