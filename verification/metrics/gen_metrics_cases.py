#!/usr/bin/env python3
"""Prints test/profiler_metrics_cases.inc: the Profiler metrics' expected
values, computed independently of the simulator.

For every program the mini ISS can run (cache/miniiss.py: the cache-lab
programs and the scheduler demos), from the instruction-by-instruction
trace of retired PCs:
  - retired instructions, by mnemonic, loads and stores;
  - branches retired (blt/bne/beq) and how many were taken: the next
    retired PC is not the branch PC + 4;
  - loops: every backward branch or jal (target <= its own PC); iterations =
    times the target executed; dynamic instructions = executions of the PCs
    from the target to the branch; the top three by dynamic instructions.
For every cache-lab program x lab configuration (cache/oracle.py), the L1
data misses split by cause with the textbook "3C" definitions:
  - compulsory: the first access to the block;
  - capacity: otherwise, and a fully associative LRU cache with the same
    number of lines and the same allocation policy also misses;
  - conflict: the rest.
usage: gen_metrics_cases.py > test/profiler_metrics_cases.inc
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "cache"))
sys.path.insert(0, os.path.join(HERE, "..", "lib"))
import cachemodel  # noqa: E402
import miniiss  # noqa: E402
import oracle  # noqa: E402
import vpaths  # noqa: E402

BRANCHES = {"blt", "bne", "beq"}
LOADS = {"lb", "lbu", "lh", "lhu", "lw", "lwu", "ld", "flw", "fld"}
STORES = {"sb", "sh", "sw", "sd", "fsw", "fsd"}


def programs():
    out = []
    for sub in ("cache_lab", "scheduler"):
        d = os.path.join(vpaths.ROOT, "examples", sub)
        out += [f"{sub}/{f}" for f in sorted(os.listdir(d)) if f.endswith(".s")]
    return out


def target_of(insn, pc, labels):
    op, a = insn
    if op in BRANCHES:
        return labels[a[2]] * 4
    if op == "jal":
        return labels[a[-1]] * 4
    return None


def profile(text):
    insns, labels = miniiss.parse(text)
    pcs = miniiss.run(text)["fetch"]  # every executed PC, in order (no pipeline)
    counts = {}
    for pc in pcs:
        counts[pc] = counts.get(pc, 0) + 1
    mnem, branches, taken = {}, 0, 0
    for i, pc in enumerate(pcs):
        op = insns[pc // 4][0]
        mnem[op] = mnem.get(op, 0) + 1
        if op in BRANCHES:
            branches += 1
            nxt = pcs[i + 1] if i + 1 < len(pcs) else pc + 4
            taken += nxt != pc + 4
    loops = []
    for pc, insn in enumerate(insns):
        pc *= 4
        t = target_of(insn, pc, labels)
        if t is not None and t <= pc and counts.get(pc):
            dyn = sum(counts.get(p, 0) for p in range(t, pc + 4, 4))
            loops.append((dyn, t, pc, counts.get(t, 0)))
    loops.sort(key=lambda x: (-x[0], x[1], x[2]))
    return pcs, mnem, branches, taken, loops[:3]


def three_c(events, spec):
    sets, ways, line, pol, wb, wa = spec
    real = cachemodel.Cache(sets, ways, line, pol, bool(wb), bool(wa))
    full = cachemodel.Cache(1, sets * ways, line, "LRU", bool(wb), bool(wa))
    seen, comp, cap, conf = set(), 0, 0, 0
    for kind, addr, size, rw in events:
        if kind != "D":
            continue
        block = addr // line
        hit = real.access(addr, size, rw)
        full_hit = full.access(addr, size, rw)
        if not hit:
            if block not in seen:
                comp += 1
            elif not full_hit:
                cap += 1
            else:
                conf += 1
        seen.add(block)
    return real.misses, comp, cap, conf, len(seen)


def main():
    out = ["// Generated by verification/metrics/gen_metrics_cases.py from the mini ISS",
           "// (verification/cache/miniiss.py) and the textbook cache model, never from the",
           "// simulator. Do not edit by hand.",
           "// kMixCases: { program, retired, branches, taken, loads, stores,",
           "//   \"mnemonic=count ...\", \"targetPc:branchPc:iterations:dynamic ...\" (top 3) }"]
    out.append("const MetricsMixCase kMixCases[] = {")
    for prog in programs():
        text = open(os.path.join(vpaths.ROOT, "examples", prog)).read()
        pcs, mnem, br, tk, loops = profile(text)
        loads = sum(c for m, c in mnem.items() if m in LOADS)
        stores = sum(c for m, c in mnem.items() if m in STORES)
        ms = " ".join(f"{m}={c}" for m, c in sorted(mnem.items(), key=lambda x: (-x[1], x[0])))
        ls = " ".join(f"{t}:{b}:{it}:{dyn}" for dyn, t, b, it in loops)
        out.append(f'    {{"{prog}", {len(pcs)}, {br}, {tk}, {loads}, {stores}, "{ms}", "{ls}"}},')
    out.append("};")
    out.append("// kMissCases: { program, config, sets, ways, lineBytes, fifo, writeBack,")
    out.append("//   writeAllocate, L1 misses, compulsory, capacity, conflict, distinct blocks }")
    out.append("const MetricsMissCase kMissCases[] = {")
    for prog in [p for p in programs() if p.startswith("cache_lab/")]:
        events = oracle.miniiss.run(open(os.path.join(vpaths.ROOT, "examples", prog)).read())["events"]
        for name, spec in oracle.CONFIGS.items():
            sets, ways, line, pol, wb, wa = spec
            m, c, cap, conf, blocks = three_c(events, spec)
            out.append(f'    {{"{prog}", "{name}", {sets}, {ways}, {line}, {str(pol == "FIFO").lower()}, '
                       f'{str(bool(wb)).lower()}, {str(bool(wa)).lower()}, {m}, {c}, {cap}, {conf}, {blocks}}},')
    out.append("};")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
