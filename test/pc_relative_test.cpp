bool owes(const PcCase &c, Model model)
{
    const std::string owe = c.owe;
    if (owe == "padded")
        return true;
    if (owe == "chain")
        return model != Model::Rv5NhNf;
    const bool load = owe.rfind("load:", 0) == 0;
    const int distance = owe.back() - '0';
    switch (model)
    {
    case Model::Rvss:
    case Model::Rv5HNf:
    case Model::Rv5HF:
        return true;
    case Model::Rv5NhF:
        return !load || distance >= 1;
    case Model::Rv5NhNf:
        return distance == 2;
    }
    return false;
}

std::unique_ptr<ProcessorBase> run(Model model, const QTemporaryDir &dir, const std::string &text)
{
    const std::string path =
        dir.path().toStdString() + "/pc" + std::to_string(fileSerial++) + ".s";
    {
        std::ofstream file(path);
        file << text;
    }
    setupVmStateDirectory();
    auto processor = makeProcessor(model);
    processor->LoadProgram(assemble(path));
    processor->DebugRun();
    return processor;
}

struct Param
{
    std::size_t index;
    Model       model;
};

/// Readable in gtest output and in the ctest names gtest_discover_tests builds.
void PrintTo(const Param &param, std::ostream *os)
{
    *os << kCases[param.index].name << "/" << name(param.model);
}

std::vector<Param> owedParams()
{
    std::vector<Param> out;
    for (std::size_t i = 0; i < std::size(kCases); ++i)
        for (Model model : allModels())
            if (owes(kCases[i], model))
                out.push_back({i, model});
    return out;
}
