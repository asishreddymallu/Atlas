{
};

INSTANTIATE_TEST_SUITE_P(Owed, PcRelative, testing::ValuesIn(owedParams()),
                         [](const testing::TestParamInfo<Param> &info)
                         {
                             std::string label = std::string(kCases[info.param.index].name) +
                                                 "_" + name(info.param.model);
                             for (char &c : label)
                                 if (c == '-')
                                     c = '_';
                             return label;
                         });

TEST_P(PcRelative, MatchesTheLayoutAndRvss)
{
    const PcCase &c = kCases[GetParam().index];
    const Model model = GetParam().model;
    QTemporaryDir dir;
    ASSERT_TRUE(dir.isValid());
    std::unique_ptr<ProcessorBase> got;
    std::unique_ptr<ProcessorBase> reference;
    ASSERT_NO_THROW(got = run(model, dir, c.program)) << "the program did not assemble";
    ASSERT_NO_THROW(reference = run(Model::Rvss, dir, c.program));
    for (const auto &[reg, value] : c.expected)
    {
        const uint64_t actual = got->registers_.ReadGpr(reg);
        EXPECT_EQ(actual, value) << name(model) << " x" << reg << " = " << hex(actual, 16)
                                 << ", the layout says " << hex(value, 16);
        EXPECT_EQ(actual, reference->registers_.ReadGpr(reg))
            << name(model) << " x" << reg << " differs from rvss";
    }
}
