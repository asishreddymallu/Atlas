/**
 * @file pc_relative_test.cpp
 * @brief PC-relative and control-flow instructions on all five models:
 *        auipc, la, jal/jalr links and targets, j/jr/ret, the six branches
 *        taken and not taken in both directions, and jalr fed by a producer
 *        at distance 0, 1 and 2.
 *
 * known_issues 103: the four pipelines computed auipc as reg1 + reg2 - the
 * register fields are immediate bits there - and never added the PC, so
 * auipc wrote 0 and `la` produced only its low 12 bits. rvss was right.
 *
 * Every expected value is computed INDEPENDENTLY of the simulator, by
 * ~/atlas-verify/pcrel/gen.py (out of tree), which lays out each program
 * and counts its instructions: an instruction's address is 0 + 4 * index,
 * a .data label's is 0x10000000 + offset, and a branch's outcome comes
 * from Python's own signed/unsigned comparison. The table below is that
 * script's output, pasted. Each test additionally asserts that the model
 * agrees with rvss.
 *
 * ── what each model owes (one test per owed case and model) ────────────
 *
 *   padded     every model. Dependent pairs carry four nops, which is the
 *              contract of the no-hazard variants.
 *   chain      every model but nh_nf: `la` expands to auipc + addi with no
 *              gap between them, emitted by the assembler, so - like a
 *              multi-instruction li (known_issues 77) - nh_nf cannot run it
 *              whatever the source says.
 *   alu:d      jalr reads a register an ALU instruction wrote d nops before.
 *              rvss, h_nf, h_f and nh_f at every d (nh_f forwards an ALU
 *              result at distance 0); nh_nf only at d = 2, its contract's
 *              two nops (rv5s_processor_nh_nf.cpp:5).
 *   load:d     the same with a load producer. nh_f only at d >= 1 - a
 *              load's value does not exist until MEM and nh_f has no hazard
 *              unit to wait for it (known_issues 77) - and nh_nf at d = 2.
 *
 * Not covered, and why: `call` and `tail` do not assemble on any model
 * (no pseudo-instruction arm exists for them), and `la` of a .text label
 * is rejected by the assembler by design. Both are recorded in
 * known_issues; jal/ret stand in for call.
 */
