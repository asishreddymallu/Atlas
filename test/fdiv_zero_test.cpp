/**
 * @file fdiv_zero_test.cpp
 * @brief fdiv.s and fdiv.d by zero, by infinity and with NaN operands, on all
 *        five models (known_issues 75).
 *
 * IEEE 754 and RISC-V: a finite non-zero x divided by +-0 is +-inf (the sign
 * is the XOR of the operands' signs); 0/0 and inf/inf are invalid and give
 * the canonical NaN (0x7FC00000 / 0x7FF8000000000000); any NaN operand gives
 * the canonical NaN. The ALU used to return a NaN for every zero divisor.
 *
 * Expected bits come from ~/atlas-verify/e4/gen_fdiv.py, an oracle written
 * from the spec. Singles sit zero-extended in the f register (71). The flags
 * are not asserted: fflags is still the pre-RISC-V encoding with replace
 * semantics (72, kept open by decision).
 */
