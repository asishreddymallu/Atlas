class Fclass : public testing::TestWithParam<IsaParam>
{
};

INSTANTIATE_TEST_SUITE_P(AllModels, Fclass, testing::ValuesIn(isaParams(kCases, allModels())),
                         [](const testing::TestParamInfo<IsaParam> &info)
                         { return isaParamName(kCases, info.param); });

TEST_P(Fclass, MaskMatchesTheSpec)
{
    QTemporaryDir dir;
    ASSERT_TRUE(dir.isValid());
    expectIsaCase(kCases[GetParam().index], GetParam().model, dir);
}

TEST(FclassEncoding, WordsMatchTheSpecLayout)
{
    QTemporaryDir dir;
    ASSERT_TRUE(dir.isValid());
    for (const auto &e : kEncodings)
    {
        std::vector<uint32_t> words;
        ASSERT_NO_THROW(words = encode(dir, std::string(".text\n    ") + e.line + "\n"))
            << e.line << " did not assemble";
        ASSERT_EQ(words.size(), 1u) << e.line;
        EXPECT_EQ(words[0], e.word) << e.line << ": " << hex(words[0], 8) << ", the spec says "
                                    << hex(e.word, 8);
    }
}
