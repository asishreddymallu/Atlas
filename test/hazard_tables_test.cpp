/**
 * @file hazard_tables_test.cpp
 * @brief The hazard unit's per-opcode tables against the RISC-V spec, one
 *        test per mnemonic (E6; the tables came in E5 for known_issues 78/105).
 *
 * For every mnemonic the assembler accepts, one line with distinctive fields
 * is assembled here, and every word of it is checked against a row written
 * from the RISC-V spec in ~/atlas-verify/e6/gen_tables.py:
 *   - instruction_set::sourceRegisters: which of rs1/rs2/rs3 it reads, and
 *     from which file. A missing read is a missed stall, an extra one a
 *     false stall;
 *   - the hazard unit's view of the producer: producerWritesGpr and
 *     producerWritesFpr, fed the flags decode latches for that word
 *     (rv5s_processor_base.cpp:325-327: the control unit's reg_write, and
 *     freg_write = isF || isD).
 * Pseudos are checked word by word through their expansion.
 *
 * One deliberate exception, pinned with its reason: a CSR instruction writes
 * rd in the integer file, but the control unit sets no reg_write for SYSTEM.
 * serve_csr_at_writeback writes rd itself and flushes every younger
 * instruction, so no consumer can be in flight; the hazard unit not seeing
 * a producer is harmless. Whether to change that is known_issues 119.
 */
