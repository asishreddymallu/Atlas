/**
 * @file csr_test.cpp
 * @brief csrrw/csrrs/csrrc and their immediate forms on fflags, frm and fcsr,
 *        on all five models (known_issues 104).
 *
 * The pipelines executed every CSR instruction as a no-op (and nh-nf ran
 * the instruction before it twice). A CSR instruction is now served at
 * writeback, serializing, like an ecall: everything older has retired, the
 * CSR is read and written there, rd gets the old value, and the younger
 * stages are flushed and refetched from pc + 4.
 *
 * Expected values come from ~/atlas-verify/e4/gen_csr.py, a Python model of
 * fcsr written from the spec: fflags = fcsr[4:0], frm = fcsr[7:5];
 * csrrw(i) with rd = x0 does not read; csrrs/csrrc(i) with rs1 = x0 (uimm 0)
 * do not write. Every result is stored to scratch right after its CSR
 * instruction.
 *  - SixForms_*: all six forms from two starting values, with read-backs.
 *  - ZeroRegisterRules, Aliasing.
 *  - FrmOrdering_s/d: an FP op after a frm write uses the new mode, one
 *    before it the old one (1 + half an ulp: RNE ties to even, RUP rounds up).
 *  - YoungerFpOpDoesNotLeak: an fflags read is not overtaken by the fdiv
 *    right behind it.
 * The unpadded variants run back to back on the models that handle hazards
 * (rvss and the three with a hazard unit or forwarding).
 */
