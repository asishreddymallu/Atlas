/**
 * @file hdu_false_stall_test.cpp
 * @brief The hazard unit stalls only for a register the consumer really
 *        reads, in the file the producer really writes (known_issues 78, 105).
 *
 * check_data_hazard used to compare bits 19:15, 24:20 and 31:27 of EVERY
 * instruction against both the integer and the FP destination in flight, so
 * an f5 load stalled an `addi` reading x5, and lui/auipc/jal stalled on their
 * immediate bits. Timing only: no value changed.
 *
 * Each case puts a producer directly in front of a consumer. Cycle counts on
 * h_nf and h_f come from ~/atlas-verify/e5/gen_hdu.py, which applies the
 * pipeline rules (ID-to-WB distance 3 without forwarding, load-use 1 with it,
 * 2 bubbles per jal, cycles = last ID + 3) to spec-written read/write sets -
 * not from the simulator. LoadThenUse and FlwThenFpUse are real dependencies
 * and must still stall. The programs are unpadded, so values are checked on
 * the models that own hazards: rvss, h_nf and h_f.
 */
