// ───────── the host's rounding mode survives a run ─────────

class HostRoundingMode : public testing::TestWithParam<Model>
{
};
INSTANTIATE_TEST_SUITE_P(AllModels, HostRoundingMode, testing::ValuesIn(allModels()),
                         [](const testing::TestParamInfo<Model> &info)
                         {
                             std::string label = name(info.param);
                             for (char &c : label)
                                 if (c == '-')
                                     c = '_';
                             return label;
                         });

TEST_P(HostRoundingMode, IsUnchangedAfterARun)
{
    // The floating-point environment belongs to the thread that runs the
    // instructions: the Run worker, or the GUI thread itself when the user
    // steps (ProcessorManager::step). DebugRun here runs on this thread.
    QTemporaryDir dir;
    ASSERT_TRUE(dir.isValid());
    const std::string program = std::string(".data\nv: .dword 0x3FF8000000000000, 1\n.text\n") +
                                "    lui x10, 0x10000\n" + kGap + "    fld f1, 0(x10)\n" + kGap +
                                "    fld f2, 8(x10)\n" + kGap + "    fadd.d f3, f1, f2\n" + kGap +
                                "    fadd.d f4, f1, f2, rtz\n" + kGap + "    fsd f3, 16(x10)\n" +
                                kGap + "    flw f5, 0(x10)\n" + kGap;
    for (int mode : {FE_DOWNWARD, FE_TONEAREST, FE_TOWARDZERO, FE_UPWARD})
    {
        ASSERT_EQ(std::fesetround(mode), 0);
        auto p = runIsaProgram(GetParam(), dir, program);
        const int after = std::fegetround();
        std::fesetround(FE_TONEAREST);
        EXPECT_EQ(after, mode) << name(GetParam()) << ": the host mode was " << mode
                               << " before the run and " << after << " after";
    }
}
