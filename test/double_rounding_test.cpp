TEST(DoubleConversions, ExplicitRoundingModesAssembleAsTheSpecLaysThemOut)
{
    QTemporaryDir dir;
    ASSERT_TRUE(dir.isValid());
    for (const ConvEncoding &c : kConvRm)
    {
        std::vector<uint32_t> words;
        try
        {
            words = encode(dir, std::string(".text\n    ") + c.line + "\n");
        }
        catch (const std::exception &)
        {
            ADD_FAILURE() << c.line << ": did not assemble";
            continue;
        }
        ASSERT_EQ(words.size(), 1u) << c.line;
        EXPECT_EQ(words[0], c.word) << c.line << ": " << hex(words[0], 8) << ", the spec says "
                                    << hex(c.word, 8);
    }
}

