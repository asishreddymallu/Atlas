/**
 * @file double_rounding_test.cpp
 * @brief Double-precision results are correctly rounded in the mode the
 *        instruction asks for, on all five models, and running a program
 *        leaves the host's rounding mode as it found it (known_issues 107).
 *
 * Two defects, compounding on rvss:
 *   - RVSSProcessor::ExecuteDouble passed rm through without mapping DYN
 *     (0b111, the assembler's default) to frm, as ExecuteFloat and the
 *     pipelines do;
 *   - Alu::fpexecute/dfpexecute set the host rounding mode from rm and
 *     restored it on only some return paths. The fld/fsd address add
 *     returned early with fld's funct3 (0b011, RUP) applied, so the thread
 *     stayed in round-up. With rm = DYN unmapped, rvss's next fadd.d
 *     inherited it.
 *
 * Tables generated by ~/atlas-verify/e3/gen_dround.py:
 *   kDyn   DYN with frm = 0, after an fld; oracle: Python's IEEE doubles
 *          (round-to-nearest-even).
 *   kModes explicit rtz/rdn/rup/rmm for fadd.d, fmul.d and fcvt.l.d;
 *          oracle: the exact Fraction result rounded by the mode's rule.
 *          RMM ties are not here: the ALU has no RMM and falls back to the
 *          host mode, which differs from RMM only on an exact tie
 *          (known_issues 113).
 *   kConvRm the eight D conversions with an explicit rounding mode, and
 *          the word the spec's OP-FP layout gives. Their syntax rows named
 *          the wrong operand classes, so none assembled (known_issues 114),
 *          and fcvt.l.d's explicit modes could not be tested at all.
 * fcsr is not checked: known_issues 108 stays open with 72.
 */
