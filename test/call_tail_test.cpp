TEST(CallTailEncoding, CallIsJalRaAndTailIsJalX0)
{
    // jal rd, +8: imm[10:1] = 4 in bits 30:21, rd in 11:7, opcode 0x6F.
    QTemporaryDir dir;
    ASSERT_TRUE(dir.isValid());
    std::vector<uint32_t> words;
    ASSERT_NO_THROW(words = encode(dir, ".text\n    call f\n    tail f\nf:\n    nop\n"));
    ASSERT_EQ(words.size(), 3u);
    EXPECT_EQ(words[0], (4u << 21) | (1u << 7) | 0x6Fu) << "call f: " << hex(words[0], 8);
    EXPECT_EQ(words[1], (2u << 21) | (0u << 7) | 0x6Fu) << "tail f: " << hex(words[1], 8);
}

TEST(CallTailEncoding, LaOfATextLabelIsRejectedAndSaysWhy)
{
    QTemporaryDir dir;
    ASSERT_TRUE(dir.isValid());
    const auto errors = parseErrors(dir, ".text\n    la x5, here\nhere:\n    nop\n");
    ASSERT_FALSE(errors.empty()) << "la of a .text label was accepted";
    EXPECT_NE(errors[0].message.find(".data"), std::string::npos) << errors[0].message;
    EXPECT_NE(errors[0].message.find("here"), std::string::npos)
        << "the message should name the label: " << errors[0].message;
}
