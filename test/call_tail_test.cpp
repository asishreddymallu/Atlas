std::vector<ParseError> parseErrors(const QTemporaryDir &dir, const std::string &source)
{
    const std::string path = dir.path().toStdString() + "/pe" + std::to_string(fileSerial++) + ".s";
    {
        std::ofstream out(path);
        out << source;
    }
    Lexer lexer(path);
    auto tokens = lexer.getTokenList();
    Parser parser(path, tokens);
    try
    {
        parser.parse();
    }
    catch (const std::exception &)
    {
        // the parser throws once it has recorded an error
    }
    return parser.getErrors();
}
